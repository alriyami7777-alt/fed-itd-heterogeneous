"""E-11 (TWOS as fifth member) summary at 20 seeds. Every number is computed here from
results/review2/stats_e11.csv (r2_stats.py e11), e11_twos_cells.csv and e11_twos_per_seed.csv (e11_extra.py 0-19).
TWOS appears only as group-level numbers (no per-user or per-day values)."""
import os as _os, sys as _sys  # repository layout: modules live in ../../src and ../
_HERE = _os.path.dirname(_os.path.abspath(__file__))
_sys.path[:0] = [_os.path.join(_HERE, "..", "..", "src"), _os.path.join(_HERE, "..")]
from config import ROOT as _ROOT
_os.chdir(_ROOT)  # relative paths below (results/) are relative to FITD_ROOT
import pandas as pd

R = "results/review2"
S = pd.read_csv(f"{R}/stats_e11.csv")
C = pd.read_csv(f"{R}/e11_twos_cells.csv")
P = pd.read_csv(f"{R}/e11_twos_per_seed.csv", index_col=[0, 1])
NM = {"C1+C2+C3+C4+C5": "All five", "C1+C5": "TWOS + CERT r4.2", "C2+C5": "TWOS + CERT r5.2", "C3+C5": "TWOS + SPEDIA",
      "C4+C5": "TWOS + LANL"}
RL = {"fedavg_equal": "FedAvg (equal)", "fedavg_size": "FedAvg (size)", "fedper_in": "Private first layer"}
REF = {"R1_pooled": "Pooled data, all five (no privacy)", "R6_loo": "Leave-one-out FedAvg of the other four",
       "R5_zeroshot": "Single source, zero-shot", "R0_XGB": "XGBoost, TWOS only", "R0_RF": "Random forest, TWOS only"}
f3, sg = (lambda x: f"{x:.3f}"), (lambda x: f"{x:+.3f}")
loc = C[C.regime == "R0_local"].iloc[0]
out = []
w = out.append
fed = S[S.family == "E-11 federated"]
tw = fed[fed.client == "TWOS"]
nseeds = int(tw.n_seeds.iloc[0])

w(f"# E-11 summary: TWOS as a fifth member, {nseeds} seeds (25 Oct 2026)\n")
w("Generated by `summarise_e11.py` from `stats_e11.csv`, `e11_twos_cells.csv` and "
  "`e11_twos_per_seed.csv`. Day split (train Mon–Tue, validation Wed, test Thu–Fri). Effects vs each member's own local "
  "MLP: paired bootstrap over seeds (10,000, seed 20261014), paired t, Holm within each family. TWOS is reported only "
  "as group-level numbers (TWOS licence: academic use, no redistribution).\n")

w(f"## 1. TWOS test set and local baselines")
w(f"- Test set: {int(C.k.iloc[0] and 46)} user-days" if False else
  f"- TWOS test positives: {int(loc.test_pos)} positive user-days; top 10% of test user-days = {int(loc.k)} user-days.")
for r in ("R0_local", "R0_XGB", "R0_RF"):
    x = C[C.regime == r].iloc[0]
    w(f"- {'MLP, TWOS only' if r == 'R0_local' else REF[r]}: PR-AUC {f3(x.pr_auc)} ({int(x.n_seeds)} seeds; user-level 95% "
      f"interval {f3(x.user_lo)}–{f3(x.user_hi)}); test positives in its top 10%: {x.top10pct_hits_mean:.2f} of {int(x.test_pos)}.")
w("")

w("## 2. Federation vs TWOS's own MLP (TWOS member)")
w("| Group | Rule | TWOS PR-AUC | Difference vs local | Seed bootstrap 95% CI | Holm | User bootstrap 95% CI of the difference | Positives in top 10% (of 6) | Seeds above local |")
w("|---|---|---|---|---|---|---|---|---|")
lp = P.loc[("twos", "R0_local")]
for g in NM:
    for rule in RL:
        s = tw[(tw.federation == g) & (tw.comparison == f"{rule} − local")].iloc[0]
        c = C[(C.federation == g) & (C.regime == rule)].iloc[0]
        above = int((P.loc[(g, rule)] > lp).sum())
        w(f"| {NM[g]} | {RL[rule]} | {f3(s.new)} | {sg(s['diff'])} | [{sg(s.boot_lo)}, {sg(s.boot_hi)}] | {s.verdict_holm} | "
          f"[{sg(c.diff_user_lo)}, {sg(c.diff_user_hi)}] | {c.top10pct_hits_mean:.2f} | {above} of {nseeds} |")
pos = int((tw['diff'] > 0).sum())
bg = int((tw.verdict == "gain").sum())
hg = int((tw.verdict_holm == "gain").sum())
cells = C[C.regime.isin(RL) & C.federation.isin(NM)]
ug = int((cells.diff_user_lo > 0).sum())
w(f"\nCounts over the {len(tw)} TWOS cells: higher than local in {pos}; seed-bootstrap gain in {bg}; Holm gain in {hg}; "
  f"user-bootstrap interval of the difference above 0 in {ug}.\n")

w("## 3. Non-federated references for TWOS")
w("| Reference | TWOS PR-AUC | Difference vs local | Holm | Positives in top 10% |")
w("|---|---|---|---|---|")
refs = S[S.family == "E-11 references (R1/R5/R6)"]
for _, s in refs[refs.client == "TWOS"].iterrows():
    reg = s.comparison.split(" − ")[0]
    c = C[(C.federation == s.federation)].iloc[0]
    name = REF.get(reg, reg) + (f" ({s.federation.split('->')[0]})" if reg == "R5_zeroshot" else "")
    w(f"| {name} | {f3(s.new)} | {sg(s['diff'])} | {s.verdict_holm} | {c.top10pct_hits_mean:.2f} |")
w("")

w("## 4. The other members in the TWOS groups (federated vs own local MLP)")
w("| Member | Group | FedAvg (equal) | FedAvg (size) | Private first layer |")
w("|---|---|---|---|---|")
for cl in ("CERT r4.2", "CERT r5.2", "SPEDIA", "LANL"):
    for g in NM:
        x = fed[(fed.client == cl) & (fed.federation == g)]
        if x.empty:
            continue
        cell = lambda r: (lambda s: f"{sg(s['diff'])} ({s.verdict_holm.replace('no clear difference', 'n.c.d.')})")(
            x[x.comparison == f"{r} − local"].iloc[0])
        w(f"| {cl} | {NM[g]} | {cell('fedavg_equal')} | {cell('fedavg_size')} | {cell('fedper_in')} |")
w("\nVerdicts in brackets are after Holm (n.c.d. = no clear difference).\n")

us = S[S.family == "E-11 federated user-split sensitivity"]
w(f"## 5. User-disjoint split sensitivity ({int(us.n_seeds.iloc[0])} seeds, exploratory, all five members)")
w("| Member | local | FedAvg (equal) | FedAvg (size) | Private first layer |")
w("|---|---|---|---|---|")
for cl in ("TWOS", "CERT r4.2", "CERT r5.2", "SPEDIA", "LANL"):
    x = us[us.client == cl]
    g = lambda r: (lambda s: f"{f3(s.new)} ({sg(s['diff'])}, {s.verdict_holm.replace('no clear difference', 'n.c.d.')})")(
        x[x.comparison == f"{r} − local"].iloc[0])
    w(f"| {cl} | {f3(x.base.iloc[0])} | {g('fedavg_equal')} | {g('fedavg_size')} | {g('fedper_in')} |")
w("")

best = tw.loc[tw.new.idxmax()]
w("## 6. Reading")
w(f"- **Federation lifts TWOS.** TWOS is higher than its own MLP ({f3(loc.pr_auc)}) in {pos} of {len(tw)} federated cells; "
  f"the best is the {RL[best.comparison.split(' − ')[0]].lower()} with all five members, {f3(best.new)} ({sg(best['diff'])}, "
  f"Holm). {hg} cells hold after Holm; {ug} have a user-level interval above 0.")
w(f"- **The private first layer is the most dependable rule for TWOS**: it is higher than local in every group and its "
  f"user-level interval is above 0 in " + str(int((cells[cells.regime == 'fedper_in'].diff_user_lo > 0).sum())) + " of 5 groups.")
w(f"- The best federated TWOS scores are above every non-federated reference (not tested against them directly): pooled data {f3(refs[(refs.client == 'TWOS') & refs.comparison.str.startswith('R1')].new.iloc[0])}, "
  f"leave-one-out {f3(refs[(refs.client == 'TWOS') & refs.comparison.str.startswith('R6')].new.iloc[0])}, XGBoost "
  f"{f3(C[C.regime == 'R0_XGB'].pr_auc.iloc[0])} (5 seeds); none of these is clearly above the TWOS MLP.")
w("- The other members behave as in the four-member study: SPEDIA loses, CERT r5.2 loses in the five-member group, "
  "LANL stays near zero.")
w("- Caveat: the TWOS test set is small (6 positive user-days from 6 users), so the user-level intervals are wide; and on a "
  "user-disjoint split (exploratory, 5 seeds) TWOS's local model is much stronger and only the private first layer stays level.")
open("results/review2/summary_e11.md", "w").write("\n".join(out) + "\n")
print("\n".join(out))
