"""E-3 Ditto summary (20 seeds), follow-up to summarise_e3.py. All numbers computed here.
Inputs: results/review2/stats_e3.csv (r2_stats.py e3: FedPer-H, FedPer-2, Ditto vs own local MLP, Holm within the
57 E-3 comparisons), results/review2/e3_interim_vs_local.csv (from summarise_e3.py), e3_ditto_s*.csv, e3_ditto_lambda.json,
results/review/fedper_in_s*.csv. Writes results/review2/e3_ditto_vs_input.csv and results/review2/summary_e3_ditto.md."""
import os as _os, sys as _sys  # repository layout: modules live in ../../src and ../
_HERE = _os.path.dirname(_os.path.abspath(__file__))
_sys.path[:0] = [_os.path.join(_HERE, "..", "..", "src"), _os.path.join(_HERE, "..")]
from config import ROOT as _ROOT
_os.chdir(_ROOT)  # relative paths below (results/) are relative to FITD_ROOT
import json

import numpy as np
import pandas as pd

from r2_stats import NAMES, paired, rd, rd_rev
from review_stats import holm

S = pd.read_csv("results/review2/stats_e3.csv")
I = pd.read_csv("results/review2/e3_interim_vs_local.csv")
lam = json.load(open("results/review2/e3_ditto_lambda.json"))
dd, di = rd("e3_ditto"), rd_rev("fedper_in")
GROUPS = ["C1+C2", "C1+C3", "C2+C3", "C3+C4", "C1+C4", "C2+C4", "C1+C2+C3", "C1+C2+C3+C4"]
MEM = {"C1": "cert42", "C2": "cert52", "C3": "spedia", "C4": "lanl"}
ORDER = ["cert42", "cert52", "spedia", "lanl"]
INV = {v: k for k, v in NAMES.items()}
D = S[S.comparison == "ditto − local"].copy()
D["c"] = D.client.map(INV)

H = []
for g in GROUPS:
    for c in [MEM[m] for m in g.split("+")]:
        a, b = dd[(dd.federation == g) & (dd.client == c)], di[(di.federation == g) & (di.client == c)]
        if len(a) and len(b):
            r = paired(a.set_index("seed").pr_auc, b.set_index("seed").pr_auc, group=g, client=c)
            if r:
                H.append(r)
H = pd.DataFrame(H)
H["t_p_holm"] = holm(H.t_p.to_numpy())
H["verdict_holm"] = np.where(H.t_p_holm < 0.05, np.where(H["diff"] > 0, "Ditto higher", "private first layer higher"),
                             "no clear difference")
H.to_csv("results/review2/e3_ditto_vs_input.csv", index=False)

f3, sg = (lambda x: f"{x:.3f}"), (lambda x: f"{x:+.3f}")
V = {"gain": "gain", "loss": "loss", "no clear difference": "n.c.d."}
out = []
w = out.append
w(f"# E-3 Ditto summary ({int(D.n_seeds.min())} seeds, 26 Oct 2026)\n")
w("Generated by `summarise_e3_ditto.py`. Ditto: every member keeps a full personal model, trained "
  "after each global FedAvg (size) step with a pull of strength λ towards the new global model; the reported model is the "
  f"personal one. λ = {lam['C1+C2+C3+C4']} for every group, chosen once on seed 0 in the four-member group by mean "
  "validation PR-AUC (" + ", ".join(f"λ {k}: {v:.3f}" for k, v in lam["C1+C2+C3+C4__val"].items()) + "). "
  "Effect = Ditto − the member's own local MLP, paired by seed; Holm within the 57 E-3 comparisons (FedPer-H, FedPer-2, "
  "Ditto), as in `stats_e3.csv`.\n")

w("## 1. Ditto vs own local model")
w("| Member | Group | local | Ditto | Difference [95% bootstrap CI] | Holm |")
w("|---|---|---|---|---|---|")
for c in ORDER:
    for g in GROUPS:
        x = D[(D.c == c) & (D.federation == g)]
        if len(x):
            r = x.iloc[0]
            w(f"| {r.client} | {g} | {f3(r.base)} | {f3(r.new)} | {sg(r['diff'])} [{sg(r.boot_lo)}, {sg(r.boot_hi)}] | {r.verdict_holm} |")
w(f"\nTotals ({len(D)} member cells): Holm gains {(D.verdict_holm == 'gain').sum()}, Holm losses "
  f"{(D.verdict_holm == 'loss').sum()}; bootstrap gains {(D.verdict == 'gain').sum()}, bootstrap losses {(D.verdict == 'loss').sum()}.\n")

w("## 2. All five personalisation rules side by side (mean change vs own local model over the groups)")
w("| Member | FedPer (65) | Private first layer (5,504) | FedPer-H (5,479) | FedPer-2 (8,321) | Ditto (full personal model) |")
w("|---|---|---|---|---|---|")
for c in ORDER:
    cells = [sg(I[(I.rule == k) & (I.client == c)]["diff"].mean()) for k in ("fedper", "fedper_in", "fedperh", "fedper2")]
    cells.append(sg(D[D.c == c]["diff"].mean()))
    w(f"| {NAMES[c]} | " + " | ".join(cells) + " |")
w("\nFirst four columns: `e3_interim_vs_local.csv` (from `summarise_e3.py`); Ditto: this summary. Private weights per member in brackets.\n")

w("## 3. Ditto vs the private first layer, paired by seed (Holm within these 19 cells)")
w("| Member | Group | Private first layer | Ditto | Ditto − first layer [95% CI] | Holm |")
w("|---|---|---|---|---|---|")
for c in ORDER:
    for _, r in H[H.client == c].iterrows():
        w(f"| {NAMES[c]} | {r.group} | {f3(r.base)} | {f3(r.new)} | {sg(r['diff'])} [{sg(r.boot_lo)}, {sg(r.boot_hi)}] | {r.verdict_holm} |")
w("")

sp = D[D.c == "spedia"]
spH = H[H.client == "spedia"]
w("## 4. Reading")
w(f"- **Ditto keeps every member close to its own model.** No member loses more than "
  f"{sg(D['diff'].min())}; {(D.verdict_holm == 'loss').sum()} of {len(D)} cells are Holm losses (all SPEDIA) and none is a "
  f"Holm gain. LANL shows small bootstrap gains in {(D[(D.c == 'lanl')].verdict == 'gain').sum()} of 4 groups.")
w(f"- **SPEDIA:** {f3(sp.new.min())}–{f3(sp.new.max())} against {f3(sp.base.iloc[0])} alone (mean {sg(sp['diff'].mean())}), "
  f"close to FedPer-2; Ditto is higher than the private first layer for SPEDIA in "
  f"{(spH['diff'] > 0).sum()} of {len(spH)} groups ({(spH.verdict_holm == 'Ditto higher').sum()} after Holm).")
w("- Ditto avoids most of the loss by keeping a full personal model, so it does not show that sharing helps SPEDIA; like "
  "the other rules here, it gives no member a clear gain over its own model.")
m = {k: I[(I.rule == k) & (I.client == "spedia")]["diff"].mean() for k in ("fedper", "fedperh", "fedper_in", "fedper2")}
w(f"- Together with the E-3 summary, SPEDIA's mean loss by rule: FedPer {sg(m['fedper'])}, FedPer-H {sg(m['fedperh'])}, private first "
  f"layer {sg(m['fedper_in'])}, FedPer-2 {sg(m['fedper2'])}, Ditto {sg(sp['diff'].mean())}. More personal weights go with a "
  f"smaller loss, and at equal size a private input layer does better than a private output head.")
open("results/review2/summary_e3_ditto.md", "w").write("\n".join(out) + "\n")
print("\n".join(out))

# ---- section 5: per-group lambda sensitivity (5 seeds, exploratory), added when it finished
lf = json.load(open("results/review2/e3_dittofed_lambda.json"))
X = S[S.family == "E-3 sensitivity (per-group lambda)"].copy()
X["c"] = X.client.map(INV)
add = []
a = add.append
a(f"\n## 5. Sensitivity: λ chosen separately in each group ({int(X.n_seeds.min())} seeds, exploratory)")
a("λ chosen on seed 0 by each group's own mean validation PR-AUC (same grid 0.01 / 0.1 / 1.0): " +
  ", ".join(f"{g} {lf[g]}" for g in GROUPS if g in lf) + ". Holm within these 19 comparisons.\n")
a("| Member | Group | λ | local | Ditto (per-group λ) | Difference | Holm |")
a("|---|---|---|---|---|---|---|")
for c in ORDER:
    for g in GROUPS:
        x = X[(X.c == c) & (X.federation == g)]
        if len(x):
            r = x.iloc[0]
            a(f"| {r.client} | {g} | {lf.get(g)} | {f3(r.base)} | {f3(r.new)} | {sg(r['diff'])} | {r.verdict_holm} |")
a(f"\nNo Holm gains or losses ({len(X)} cells; bootstrap: {(X.verdict == 'gain').sum()} gains, {(X.verdict == 'loss').sum()} "
  f"losses). With a per-group λ SPEDIA reaches {f3(X[X.c == 'spedia'].new.max())} in its best group, but this is a 5-seed "
  "check with λ picked on the same groups it is scored on, so it is reported only as a sensitivity result; the main "
  "Ditto result is the fixed-λ run above.")
with open("results/review2/summary_e3_ditto.md", "a") as fh:
    fh.write("\n".join(add) + "\n")
print("\n".join(add))
