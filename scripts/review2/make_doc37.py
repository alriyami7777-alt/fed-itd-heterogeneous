"""Builds the E-4 summary tables from stats_e4.csv and the per-seed files."""
import os as _os, sys as _sys  # repository layout: modules live in ../../src and ../
_HERE = _os.path.dirname(_os.path.abspath(__file__))
_sys.path[:0] = [_os.path.join(_HERE, "..", "..", "src"), _os.path.join(_HERE, "..")]
from config import ROOT as _ROOT
_os.chdir(_ROOT)  # relative paths below (results/, docs/) are relative to FITD_ROOT
import glob

import pandas as pd

R = "results/review2"
D = pd.concat(pd.read_csv(f) for f in sorted(glob.glob(f"{R}/e4_s[0-9]*.csv")))
S = pd.read_csv(f"{R}/stats_e4.csv")
W = pd.read_csv(f"{R}/e4_per_seed_winner.csv")
seeds = sorted(D.seed.unique())
FR = sorted(D.frac.unique())
VS = ["budget", "fullval"]
VSN = {"budget": "same label budget (validation = f of CERT r4.2 validation)", "fullval": "full CERT r4.2 validation set"}
OPT = ["a_local", "b_r52_as_is", "c_r52_finetune", "d_fedavg_size", "d_fedavg_equal"]
ON = {"a_local": "(a) local", "b_r52_as_is": "(b) CERT r5.2 model as is", "c_r52_finetune": "(c) CERT r5.2 + fine-tune",
      "d_fedavg_size": "(d) FedAvg size", "d_fedavg_equal": "(d) FedAvg equal"}
pct = lambda f: f"{f * 100:g}%"
f3 = lambda x: f"{x:.3f}"
sg = lambda x: f"{x:+.3f}"
out = []
w = out.append

w("# 37 — E-4 summary: label-scarce CERT r4.2 helped by CERT r5.2, 15 seeds (24 Oct 2026)\n")
w(f"Generated by `make_doc37.py` from `results/review2/e4_s*.csv` (seeds "
  f"{seeds[0]}–{seeds[-1]}, n = {len(seeds)}), `stats_e4.csv` and `e4_per_seed_winner.csv`. Test PR-AUC on the full "
  f"CERT r4.2 test set, mean over seeds. Effects: paired bootstrap (10,000, seed 20261014), paired t, Holm within each "
  f"family (6 families). \"Holm\" = still clear after Holm.\n")

w("## 1. Design (as logged, change log 2026-10-20 E-4)")
w("- CERT r4.2 keeps only f ∈ {1, 5, 10, 25}% of its training rows (label-stratified) and, in the **budget** setting, "
  "the same f of its validation rows (≥ 1 row per class, new draw per seed); the **full-validation** setting repeats "
  "everything with the full validation set. The test set is always the full CERT r4.2 test set.")
w("- Options: (a) CERT r4.2 local on the subset; (b) the CERT r5.2 local MLP used as is; (c) (b) fine-tuned on the "
  "subset (≤ 10 passes, patience 3, fresh Adam 1e-3); (d) FedAvg (size and equal) of the subset with the full CERT r5.2.")
w("- Primary outcome: (d) − the best of (a)–(c), where \"best\" = highest mean over seeds (chosen per f and setting); "
  "stricter check: (d) − the per-seed maximum of (a)–(c).\n")

w("## 2. Labels available to CERT r4.2 (mean over seeds)")
w("| f | training rows | positive training days | validation rows (budget) | positive validation days (budget) | positive validation days (full) |")
w("|---|---|---|---|---|---|")
for f in FR:
    b = D[(D.frac == f) & (D.val_set == "budget") & (D.regime == "a_local")]
    fv = D[(D.frac == f) & (D.val_set == "fullval") & (D.regime == "a_local")]
    w(f"| {pct(f)} | {b.n_train.mean():.0f} | {b.pos_train.mean():.0f} | {b.n_val.mean():.0f} | {b.pos_val.mean():.0f} | "
      f"{fv.pos_val.mean():.0f} |")
t = D[D.regime == "a_local"]
w(f"\nTest set: {int(t.n_test.iloc[0]):,} user-days, {int(t.pos_test.iloc[0])} positive (same in every run).\n")

for vs in VS:
    w(f"## {3 if vs == 'budget' else 4}. Mean test PR-AUC — {VSN[vs]}")
    w("| f | " + " | ".join(ON[o] for o in OPT) + " | best of (a)–(c) |")
    w("|---|" + "---|" * (len(OPT) + 1))
    for f in FR:
        g = D[(D.frac == f) & (D.val_set == vs)]
        m = {o: g[g.regime == o].pr_auc.mean() for o in OPT}
        best = max(OPT[:3], key=lambda o: m[o])
        w(f"| {pct(f)} | " + " | ".join(f3(m[o]) for o in OPT) + f" | {ON[best]} |")
    w("")
    w(f"**Federation − best of (a)–(c)** ({VSN[vs]}):\n")
    w("| f | rule | federated | best of (a)–(c) | difference [95% bootstrap CI] | verdict (Holm) | vs per-seed max: difference | verdict (Holm) |")
    w("|---|---|---|---|---|---|---|---|")
    for f in FR:
        for rule in ("equal", "size"):
            p = S[(S.family == f"E-4 {vs}") & (S.frac == f) & S.comparison.str.startswith(f"d_{rule} ")].iloc[0]
            q = S[(S.family == f"E-4 {vs} (per-seed max, strict)") & (S.frac == f) &
                  S.comparison.str.startswith(f"d_{rule} ")].iloc[0]
            w(f"| {pct(f)} | {rule} | {f3(p.new)} | {f3(p.base)} | {sg(p['diff'])} [{sg(p.boot_lo)}, {sg(p.boot_hi)}] | "
              f"{p.verdict_holm} | {sg(q['diff'])} | {q.verdict_holm} |")
    w("")

w("## 5. Which option wins on each seed (count of seeds, of 15)")
w("| setting | f | " + " | ".join(ON[o] for o in OPT) + " |")
w("|---|---|" + "---|" * len(OPT))
for vs in VS:
    for f in FR:
        c = W[(W.val_set == vs) & (W.frac == f)].winner.value_counts()
        w(f"| {vs} | {pct(f)} | " + " | ".join(str(int(c.get(o, 0))) for o in OPT) + " |")
w("")

w("## 6. Transfer baselines vs local (a)")
w("| setting | f | (b) − (a) | verdict (Holm) | (c) − (a) | verdict (Holm) |")
w("|---|---|---|---|---|---|")
for vs in VS:
    for f in FR:
        b = S[(S.family == f"E-4 {vs} baselines vs local") & (S.frac == f) & (S.comparison == "b_r52_as_is − a_local")].iloc[0]
        c = S[(S.family == f"E-4 {vs} baselines vs local") & (S.frac == f) & (S.comparison == "c_r52_finetune − a_local")].iloc[0]
        w(f"| {vs} | {pct(f)} | {sg(b['diff'])} | {b.verdict_holm} | {sg(c['diff'])} | {c.verdict_holm} |")
w("")

# reading, with numbers pulled from the tables
def pe(vs, f, rule="equal", fam=""):
    return S[(S.family == f"E-4 {vs}{fam}") & (S.frac == f) & S.comparison.str.startswith(f"d_{rule} ")].iloc[0]
eq_holm = [(vs, f) for vs in VS for f in FR if pe(vs, f).verdict_holm == "gain"]
sz_gain = [(vs, f) for vs in VS for f in FR if pe(vs, f, "size").verdict_holm == "gain"]
w("## 7. Reading")
w(f"- **FedAvg with equal weights is the strongest option once CERT r4.2 has ≥ 5% of its labels.** Against the best "
  f"non-federated option it gains {sg(pe('budget', 0.05)['diff'])} to {sg(pe('budget', 0.25)['diff'])} on the same label "
  f"budget and {sg(pe('fullval', 0.05)['diff'])} to {sg(pe('fullval', 0.25)['diff'])} with the full validation set; the "
  f"gain holds after Holm in {len(eq_holm)} of 8 settings ("
  + ", ".join(f"{vs} {pct(f)}" for vs, f in eq_holm) + ").")
w(f"- At 1% labels (5 positive training days) federation is level with the best option: on the same budget "
  f"{f3(pe('budget', 0.01).new)} vs {f3(pe('budget', 0.01).base)} (no clear difference).")
w(f"- **Size weighting does not help** ({len(sz_gain)} Holm gains): CERT r5.2 holds almost all the rows, so the size-"
  f"weighted model is likely close to a CERT r5.2 model (an interpretation, not tested); at 10–25% it falls below the best option.")
eqw = {(vs, f): int((W[(W.val_set == vs) & (W.frac == f)].winner == "d_fedavg_equal").sum()) for vs in VS for f in FR}
w(f"- **Per seed, FedAvg (equal) is the top option** in {eqw[('budget', 0.05)]}, {eqw[('budget', 0.1)]} and "
  f"{eqw[('budget', 0.25)]} of 15 seeds at 5%, 10% and 25% on the same budget ({eqw[('fullval', 0.05)]}, "
  f"{eqw[('fullval', 0.1)]}, {eqw[('fullval', 0.25)]} with full validation).")
w("- With very few labels (1–5%), reusing the CERT r5.2 model (as is or fine-tuned) is itself a large improvement over "
  "training CERT r4.2 alone (section 6); federation with equal weights adds to that from 5% upward.")
open("docs/37_E4_label_scarce_transfer_15seed_summary_2026-10-24.md", "w").write("\n".join(out) + "\n")
print("\n".join(out))
