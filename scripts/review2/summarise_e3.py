"""E-3 summary (FedPer-H and FedPer-2, 20 seeds) next to the private first layer and FedPer from the
main review runs (20 seeds). All numbers computed here.
Inputs: results/review2/e3_fedperh_s*.csv, e3_fedper2_s*.csv; results/review/{fedper_in,fedper,mlp_local}_s*.csv
(+ c2c4_ files for the C2+C4 group). Paired by seed vs each member's own local MLP; bootstrap and t from review_stats;
Holm (a) over the whole 4-rule x member table, (b) over the direct FedPer-H - private-first-layer comparisons.
Writes results/review2/e3_interim_vs_local.csv, e3_interim_head_vs_input.csv and results/review2/summary_e3.md."""
import os as _os, sys as _sys  # repository layout: modules live in ../../src and ../
_HERE = _os.path.dirname(_os.path.abspath(__file__))
_sys.path[:0] = [_os.path.join(_HERE, "..", "..", "src"), _os.path.join(_HERE, "..")]
from config import ROOT as _ROOT
_os.chdir(_ROOT)  # relative paths below (results/) are relative to FITD_ROOT
import numpy as np
import pandas as pd

from r2_stats import NAMES, paired, rd, rd_rev, ser
from review_stats import holm

GROUPS = ["C1+C2", "C1+C3", "C2+C3", "C3+C4", "C1+C4", "C2+C4", "C1+C2+C3", "C1+C2+C3+C4"]
RULES = [("fedper", "FedPer (private output layer)", rd_rev("fedper")),
         ("fedper_in", "Private first layer", rd_rev("fedper_in")),
         ("fedperh", "FedPer-H (private head)", rd("e3_fedperh")),
         ("fedper2", "FedPer-2 (last two layers private)", rd("e3_fedper2"))]
loc = rd_rev("mlp_local")
loc = loc[loc.federation == loc.client]
MEM = {"C1": "cert42", "C2": "cert52", "C3": "spedia", "C4": "lanl"}
ORDER = ["cert42", "cert52", "spedia", "lanl"]


def fix(r):
    r = r.copy()
    r["client"] = NAMES[r["client"]] if r["client"] in NAMES else r["client"]
    return r


rows, priv = [], {}
for key, name, d in RULES:
    priv[key] = int(d.params_local.iloc[0]) if "params_local" in d else np.nan
    for g in GROUPS:
        for c in [MEM[m] for m in g.split("+")]:
            x = d[(d.federation == g) & (d.client == c)]
            if x.empty:
                continue
            r = paired(x.set_index("seed").pr_auc, ser(loc, client=c), rule=key, rule_name=name, group=g, client=c)
            if r:
                rows.append(r)
T = pd.DataFrame(rows)
T["t_p_holm"] = holm(T.t_p.to_numpy())
T["verdict_holm"] = np.where(T.t_p_holm < 0.05, np.where(T["diff"] > 0, "gain", "loss"), "no clear difference")
T.to_csv("results/review2/e3_interim_vs_local.csv", index=False)

# direct comparison at matched size: FedPer-H - private first layer, per member cell
H = []
dh, di = RULES[2][2], RULES[1][2]
for g in GROUPS:
    for c in [MEM[m] for m in g.split("+")]:
        a, b = dh[(dh.federation == g) & (dh.client == c)], di[(di.federation == g) & (di.client == c)]
        if a.empty or b.empty:
            continue
        r = paired(a.set_index("seed").pr_auc, b.set_index("seed").pr_auc, group=g, client=c)
        if r:
            H.append(r)
H = pd.DataFrame(H)
H["t_p_holm"] = holm(H.t_p.to_numpy())
H["verdict_holm"] = np.where(H.t_p_holm < 0.05, np.where(H["diff"] > 0, "FedPer-H higher", "private first layer higher"),
                             "no clear difference")
H.to_csv("results/review2/e3_interim_head_vs_input.csv", index=False)

f3, sg = (lambda x: f"{x:.3f}"), (lambda x: f"{x:+.3f}")
V = {"gain": "gain", "loss": "loss", "no clear difference": "n.c.d."}
out = []
w = out.append
n = int(T.n_seeds.min())
w(f"# E-3 summary: where the private part sits, at matched size ({n} seeds, 25 Oct 2026)\n")
w("Generated by `summarise_e3.py`. FedPer-H and FedPer-2: review-2 runs (seeds 0–19); "
  "private first layer and FedPer: the main review runs (seeds 0–19). Every rule uses FedAvg (size) for the shared part, "
  "the same MLP, data, splits and checkpoint rule. Effect = rule − the member's own local MLP, paired by seed; bootstrap "
  "(10,000, seed 20261014) and paired t; **Holm over the whole table below** "
  f"({len(T)} comparisons). Ditto (third E-3 rule) is still running and follows in a short note.\n")

w("## 1. Private weights per member")
w("| Rule | What stays private | Private weights |")
w("|---|---|---|")
what = {"fedper": "output layer", "fedper_in": "first layer (42→128)", "fedperh": "new output head 64→83→1",
        "fedper2": "last two layers (128→64→1)"}
for key, name, _ in RULES:
    w(f"| {name} | {what[key]} | {priv[key]:,} |")
w("")

w("## 2. Change vs own local model, by member (mean over groups; per-group table in section 4)")
w("| Member | local | " + " | ".join(nm for _, nm, _ in RULES) + " |")
w("|---|---|" + "---|" * len(RULES))
for c in ORDER:
    base = T[T.client == c].base.iloc[0]
    cells = []
    for key, _, _ in RULES:
        x = T[(T.rule == key) & (T.client == c)]
        cells.append(f"{sg(x['diff'].mean())} ({(x.verdict_holm == 'gain').sum()} gain / {(x.verdict_holm == 'loss').sum()} loss of {len(x)})")
    w(f"| {NAMES[c]} | {f3(base)} | " + " | ".join(cells) + " |")
w("\nIn brackets: number of groups with a Holm gain / Holm loss, out of the groups that contain the member.\n")
w("Totals over all member cells: " + "; ".join(
    f"{nm}: {(T[T.rule == k].verdict_holm == 'gain').sum()} gains, {(T[T.rule == k].verdict_holm == 'loss').sum()} losses"
    for k, nm, _ in RULES) + ".\n")

w("## 3. Key question: at matched size, does a private head do as well as a private first layer?")
w(f"FedPer-H keeps {priv['fedperh']:,} weights private, the private first layer {priv['fedper_in']:,}. Direct paired "
  f"comparison FedPer-H − private first layer ({len(H)} member cells, Holm within these):\n")
w("| Member | Group | Private first layer | FedPer-H | FedPer-H − first layer [95% bootstrap CI] | Holm |")
w("|---|---|---|---|---|---|")
for c in ORDER:
    for _, r in H[H.client == c].iterrows():
        w(f"| {NAMES[c]} | {r.group} | {f3(r.base)} | {f3(r.new)} | {sg(r['diff'])} [{sg(r.boot_lo)}, {sg(r.boot_hi)}] | {r.verdict_holm} |")
sp = H[H.client == "spedia"]
w(f"\n**SPEDIA:** the private first layer is higher than FedPer-H in {(sp['diff'] < 0).sum()} of {len(sp)} groups "
  f"(by {sg(sp['diff'].max())} to {sg(sp['diff'].min())}); {(sp.verdict_holm == 'private first layer higher').sum()} "
  f"of these hold after Holm. Over all members: first layer higher after Holm in "
  f"{(H.verdict_holm == 'private first layer higher').sum()} cells, FedPer-H higher in {(H.verdict_holm == 'FedPer-H higher').sum()}.\n")

w("## 4. Per-group table (rule − own local model; Holm verdict)")
w("| Member | Group | local | " + " | ".join(nm for _, nm, _ in RULES) + " |")
w("|---|---|---|" + "---|" * len(RULES))
for c in ORDER:
    for g in GROUPS:
        x = T[(T.client == c) & (T.group == g)]
        if x.empty:
            continue
        cell = lambda k: (lambda r: f"{f3(r.new)} ({sg(r['diff'])}, {V[r.verdict_holm]})")(x[x.rule == k].iloc[0]) \
            if (x.rule == k).any() else "–"
        w(f"| {NAMES[c]} | {g} | {f3(x.base.iloc[0])} | " + " | ".join(cell(k) for k, _, _ in RULES) + " |")
w("\nn.c.d. = no clear difference after Holm.\n")

fi, fh, f2 = (T[T.rule == k] for k in ("fedper_in", "fedperh", "fedper2"))
spd = lambda d: d[d.client == "spedia"]
w("## 5. Reading")
w(f"- **Position matters, not only size.** With almost the same number of private weights ({priv['fedper_in']:,} vs "
  f"{priv['fedperh']:,}), SPEDIA loses much less with a private first layer (mean {sg(spd(fi)['diff'].mean())}) than with a "
  f"private output head (mean {sg(spd(fh)['diff'].mean())}); in the direct comparison the first layer is higher in all 5 "
  f"SPEDIA groups, 4 after Holm. So the first layer's advantage for SPEDIA is not explained by its size. A likely reason "
  f"(not tested here) is that the input layer is where the members' feature distributions differ most.")
w(f"- Keeping more of the end of the network private (FedPer-2, {priv['fedper2']:,} weights) also limits SPEDIA's loss "
  f"(mean {sg(spd(f2)['diff'].mean())}) and keeps the CERT members level, but it shares only the first layer "
  f"({priv['fedper_in']:,} weights), so less of the model is learned jointly; it is not a matched-size comparison.")
w(f"- FedPer (private output layer, {priv['fedper']} weights) gives SPEDIA the largest loss (mean {sg(spd(T[T.rule == 'fedper'])['diff'].mean())}).")
w("- No personalisation rule here gives SPEDIA a gain over its own model; the comparison is about how much of the loss each "
  "rule avoids.")
open("results/review2/summary_e3.md", "w").write("\n".join(out) + "\n")
print("\n".join(out))
